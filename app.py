def extract_exif_date(image):
    try:
        exif = image.getexif()
        if exif:
            for tag, val in exif.items():
                if TAGS.get(tag) == 'DateTime':
                    # Format: YYYY:MM:DD HH:MM:SS
                    return val.split(" ")[0].replace(":", "-")
    except Exception:
        pass
    return datetime.date.today().strftime("%Y-%m-%d")

